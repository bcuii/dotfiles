-- ============================================================
-- 窗口切换：把 <C-w>h 三键压成一键
-- ============================================================
vim.keymap.set("n", "<C-h>", "<C-w>h", { desc = "跳到左窗口" })
vim.keymap.set("n", "<C-j>", "<C-w>j", { desc = "跳到下窗口" })
vim.keymap.set("n", "<C-k>", "<C-w>k", { desc = "跳到上窗口" })
vim.keymap.set("n", "<C-l>", "<C-w>l", { desc = "跳到右窗口" })

-- ============================================================
-- 分屏管理（<leader> = 空格）
-- ============================================================
vim.keymap.set("n", "<leader>sv", "<C-w>v", { desc = "竖直分屏" })
vim.keymap.set("n", "<leader>ss", "<C-w>s", { desc = "水平分屏" })
-- 用 <C-w>c(:close) 而非 <C-w>q(:quit)：后者在只剩一个窗口时会直接退出 Neovim
vim.keymap.set("n", "<leader>sc", "<C-w>c", { desc = "关闭当前窗口" })
vim.keymap.set("n", "<leader>so", "<C-w>o", { desc = "只留当前窗口" })
vim.keymap.set("n", "<leader>s=", "<C-w>=", { desc = "所有窗口等分" })

-- 交换左右两个窗口的位置
vim.keymap.set("n", "<leader>sx", "<C-w>x", { desc = "交换窗口位置" })

-- ============================================================
-- 调整窗口大小（方向键，可长按连续调）
--
-- 前提：这四个键默认被 macOS 调度中心占用，已在
-- 系统设置 → 键盘 → 键盘快捷键 → 调度中心 里取消勾选：
--   Ctrl+↑ 调度中心 / Ctrl+↓ 应用程序窗口 / Ctrl+←→ 左右移一个空间
-- 若换机器或重装系统，需要重新取消，否则这四个映射收不到按键。
--
-- 方向语义同 LazyVim：作用于「当前窗口」，不是「推动分割线」。
-- 内置的 <C-w>+ - < > 仍然可用，且支持 count（如 10<C-w>>）。
-- ============================================================
vim.keymap.set("n", "<C-Up>", "<Cmd>resize +2<CR>", { desc = "增高" })
vim.keymap.set("n", "<C-Down>", "<Cmd>resize -2<CR>", { desc = "减高" })
vim.keymap.set("n", "<C-Left>", "<Cmd>vertical resize -4<CR>", { desc = "变窄" })
vim.keymap.set("n", "<C-Right>", "<Cmd>vertical resize +4<CR>", { desc = "变宽" })

-- ============================================================
-- 诊断
-- 内置已有：]d/[d 跳转、<C-w>d 浮窗。<C-w> 是窗口前缀，
-- 拿来看诊断助记很牵强，另绑一个（和 LazyVim 一致）。
-- ============================================================
vim.keymap.set("n", "<leader>cd", vim.diagnostic.open_float, { desc = "查看当前行诊断" })
